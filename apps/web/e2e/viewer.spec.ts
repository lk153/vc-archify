import { expect, test, type Page } from '@playwright/test';

// Viewer behaviour of the served artifacts (PRD §4): deep links, keyboard
// shortcuts, export, presentation/embed modes, and zero network requests.

const WORKFLOW = '/gallery/artifacts/agent-tool-call.workflow';

async function open(page: Page, url: string) {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => {
    if (m.type() === 'error') errors.push(m.text());
  });
  await page.goto(url);
  await expect(page.locator('svg[role="img"]').first()).toBeVisible();
  // Wait for the viewer's own readiness signal (fonts loaded, layout settled)
  // so interactions don't race its startup on slower browsers/runners.
  await page.evaluate(async () => {
    const viewer = (window as unknown as { Archify?: { waitForStableLayout?: () => Promise<unknown> } }).Archify;
    try {
      await viewer?.waitForStableLayout?.();
    } catch {
      /* layout never fully settled (e.g. motion); interactions still work */
    }
  });
  return errors;
}

test.describe('artifact viewer', () => {
  test('is self-contained: only the document itself is requested', async ({ page }) => {
    const requests: string[] = [];
    page.on('request', (r) => {
      if (!/^(data|blob):/.test(r.url())) requests.push(new URL(r.url()).pathname);
    });
    const errors = await open(page, WORKFLOW);
    await page.waitForLoadState('networkidle');
    expect(requests).toEqual([WORKFLOW]);
    expect(errors, 'console errors (e.g. CSP violations)').toEqual([]);
  });

  test('every featured type renders and is branded vc-archify', async ({ page }) => {
    for (const slug of [
      'web-app.architecture',
      'agent-tool-call.workflow',
      'cache-miss.sequence',
      'event-stream.dataflow',
      'deployment-release.lifecycle',
      'orders.erd',
    ]) {
      await open(page, `/gallery/artifacts/${slug}`);
      await expect(page.getByRole('img', { name: /generated by vc-archify/ })).toBeVisible();
    }
  });

  test('#focus opens the semantic passport for that node', async ({ page }) => {
    await open(page, `${WORKFLOW}#focus=planner`);
    await expect(page.getByText('Semantic passport', { exact: false })).toBeVisible();
    await expect(page.getByText('Authored reach', { exact: false })).toBeVisible();
    await expect(page.getByRole('button', { name: /copy link/i }).first()).toBeVisible();
  });

  test('#route traces the shortest path with journey controls', async ({ page }) => {
    await open(page, `${WORKFLOW}#route=user~external`);
    const route = page.getByRole('region', { name: 'User to External API' });
    await expect(route).toBeVisible();
    await expect(route).toContainText('7 nodes · 6 steps · shortest path');
    await expect(route.getByRole('button', { name: 'Route position 7 of 7: External API' })).toBeVisible();
    await expect(route.getByRole('group', { name: 'Route journey controls' })).toBeVisible();
  });

  test('keyboard shortcuts open finder, guide and toggle theme', async ({ page }) => {
    await open(page, WORKFLOW);
    await page.locator('body').click({ position: { x: 5, y: 5 } });

    await page.keyboard.press('/');
    await expect(page.getByRole('searchbox')).toBeVisible();
    await page.getByRole('searchbox').fill('approval');
    await expect(page.getByRole('dialog').filter({ has: page.getByRole('searchbox') })).toContainText('Approval Gate');
    await page.keyboard.press('Escape');
    await expect(page.getByRole('searchbox')).toBeHidden();

    await page.keyboard.press('?');
    await expect(page.getByText('Explore this system')).toBeVisible();
    await expect(page.getByText(/Find vc-archify useful/)).toBeVisible();
    await page.keyboard.press('Escape');

    const before = await page.evaluate(() => document.documentElement.dataset.theme);
    await page.keyboard.press('t');
    await expect.poll(() => page.evaluate(() => document.documentElement.dataset.theme)).not.toBe(before);
  });

  test('legend renaming maps to the real semantic kind in the lens', async ({ page }) => {
    await open(page, WORKFLOW);
    await page.getByRole('button', { name: 'Inspect Policy, 2 nodes' }).click();
    await expect(page.getByText(/2 Security nodes/)).toBeVisible();
    await expect.poll(() => page.evaluate(() => location.hash)).toContain('lens=security');
  });

  test('export menu offers every format and downloads a dual-theme SVG and a PNG', async ({ page }) => {
    await open(page, WORKFLOW);
    await page.getByRole('button', { name: 'Export diagram' }).click();
    const items = page.getByRole('menuitem');
    await expect(items.filter({ hasText: 'PNG' }).first()).toBeVisible();
    for (const format of ['JPEG', 'WebP', 'SVG · Auto', 'SVG · Light', 'SVG · Dark', 'WebM', 'Copy diagram']) {
      await expect(items.filter({ hasText: format }).first()).toBeVisible();
    }

    const svgDownload = page.waitForEvent('download');
    await items.filter({ hasText: 'SVG · Auto' }).first().click();
    const svg = await (await svgDownload).createReadStream();
    const text = await new Promise<string>((resolve) => {
      let data = '';
      svg.on('data', (chunk) => (data += chunk));
      svg.on('end', () => resolve(data));
    });
    expect(text).toMatch(/^<\?xml|<svg/);
    expect(text).toContain('prefers-color-scheme');
    expect(text).toContain('[data-theme="light"]');

    await page.getByRole('button', { name: 'Export diagram' }).click();
    const pngDownload = page.waitForEvent('download');
    await page.getByRole('menuitem').filter({ hasText: /^PNG/ }).first().click();
    const png = await pngDownload;
    expect(png.suggestedFilename()).toMatch(/\.png$/);
    const stream = await png.createReadStream();
    const head = await new Promise<Buffer>((resolve) => stream.once('data', (c) => resolve(Buffer.from(c))));
    expect(head.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a');
  });

  test('presentation and embed modes', async ({ page }) => {
    await open(page, `${WORKFLOW}?present=1`);
    await expect(page.locator('html')).toHaveAttribute('data-present', 'true');
    await open(page, `${WORKFLOW}?embed=1&theme=light`);
    await expect(page.locator('html')).toHaveAttribute('data-embed', 'true');
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await open(page, `${WORKFLOW}?embed=1&theme=dark`);
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  });

  test('ERD lists columns with SQL types and key badges', async ({ page }) => {
    await open(page, '/gallery/artifacts/orders.erd');
    const diagram = page.locator('svg[role="img"]').first();
    await expect(diagram).toContainText('customer_id');
    await expect(diagram).toContainText('numeric(12,2)');
    for (const badge of ['PK', 'FK', 'UK']) await expect(diagram).toContainText(badge);
  });

  test('legacy .html artifact URLs redirect permanently', async ({ request }) => {
    const res = await request.get('/gallery/artifacts/orders.erd.html', { maxRedirects: 0 });
    expect(res.status()).toBe(308);
    expect(res.headers().location).toMatch(/\/gallery\/artifacts\/orders\.erd$/);
  });

  test('artifacts are served with a strict CSP', async ({ request }) => {
    const res = await request.get(WORKFLOW);
    expect(res.headers()['content-security-policy']).toMatch(/^default-src 'none'; script-src 'sha256-/);
    expect(res.headers()['content-type']).toContain('text/html');
  });
});
