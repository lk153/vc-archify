// Engine gates via @vca/render: every playground example renders and passes the
// engine's structural checks, the reference diagrams match the design SVGs,
// output is deterministic, branded and self-contained.

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  artifactCsp, artifactSummary, checkArtifact, extractSvg, inlineScriptHashes, renderDiagram, validateDiagram,
} from '../src/index.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const readJson = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const sources = fs.readdirSync(path.join(ROOT, 'examples'))
  .filter((f) => f.endsWith('.json') && f !== 'upstream-manifest.json')
  .map((f) => `examples/${f}`);

// Reference designs (design/<type>/<theme>/<name>-<theme>.svg) and their IR.
const REFERENCES = [
  ['examples/web-app.architecture.json', 'architecture', 'web-app'],
  ['examples/production-deployment.architecture.json', 'architecture', 'production-deployment-ownership'],
  ['examples/agent-tool-call.workflow.json', 'workflow', 'agent-tool-call-workflow'],
  ['examples/cache-miss-request.sequence.json', 'sequence', 'cache-miss-request-sequence'],
  ['examples/event-stream.dataflow.json', 'dataflow', 'order-event-stream-topology'],
  ['examples/deployment-release.lifecycle.json', 'lifecycle', 'deployment-release-lifecycle'],
  ['examples/orders.erd.json', 'erd', 'order-management-schema'],
];

const designSummary = (type, name, theme) => {
  const svg = fs.readFileSync(path.join(ROOT, 'design', type, `${theme}_theme`, `${name}-${theme}.svg`), 'utf8');
  return artifactSummary(svg.replace(/<svg\b/, '<svg role="img"').replace(/ role="img"( [^>]*role="img")/, '$1'));
};

const cache = new Map();
const render = async (file) => {
  if (!cache.has(file)) cache.set(file, renderDiagram(readJson(file)));
  return cache.get(file);
};

describe('playground examples', () => {
  for (const file of sources) {
    it(`${file} validates, renders and passes the engine checks`, async () => {
      const ir = readJson(file);
      const report = await validateDiagram(ir);
      assert.equal(report.ok, true, JSON.stringify(report.diagnostics ?? report, null, 2));
      const { html, bytes } = await render(file);
      assert.ok(bytes > 100_000, 'artifact looks truncated');
      const check = await checkArtifact(html);
      const failed = (check.checks ?? []).filter((c) => !c.ok).map((c) => `${c.name}: ${c.details?.join('; ')}`);
      assert.equal(check.ok, true, failed.join('\n'));
    });
  }
});

describe('reference designs (design/)', () => {
  for (const [file, type, name] of REFERENCES) {
    for (const theme of ['dark', 'light']) {
      it(`${name} (${theme}) matches the rendered geometry and graph`, async () => {
        const rendered = artifactSummary((await render(file)).html);
        const design = designSummary(type, name, theme);
        assert.equal(rendered.viewBox, design.viewBox, 'viewBox');
        assert.deepEqual([...rendered.nodeIds].sort(), [...design.nodeIds].sort(), 'node ids');
        assert.deepEqual([...rendered.edges].sort(), [...design.edges].sort(), 'edges');
        assert.equal(rendered.preset, design.preset, 'visual preset');
      });
    }
  }
});

describe('artifact contract', () => {
  it('is deterministic', async () => {
    const ir = readJson('examples/orders.erd.json');
    const [a, b] = await Promise.all([renderDiagram(ir), renderDiagram(ir)]);
    assert.equal(a.sha256, b.sha256);
  });

  it('carries vc-archify branding and no upstream product links', async () => {
    const { html } = await render('examples/web-app.architecture.json');
    assert.match(html, /generated by vc-archify/);
    assert.match(html, /href="https:\/\/github\.com\/lk153\/vc-archify"/);
    assert.doesNotMatch(html, /archify\.si/);
    assert.doesNotMatch(html, /github\.com\/tt-a1i/);
    const visible = html
      .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '')
      .replace(/<style\b[^>]*>[\s\S]*?<\/style>/g, '')
      .replace(/<[^>]+>/g, ' ');
    assert.doesNotMatch(visible, /(?<![\w-])Archify\b/);
  });

  it('is self-contained (no external resources)', async () => {
    const { html } = await render('examples/agent-tool-call.workflow.json');
    const external = [...html.matchAll(/\b(?:src|href|xlink:href)="(https?:\/\/[^"]+)"/g)].map((m) => m[1]);
    assert.deepEqual(external, ['https://github.com/lk153/vc-archify'], 'only the guide credit anchor may link out');
    assert.doesNotMatch(html, /@import\s+url\(|url\(["']?https?:/);
  });

  it('works under a hash-based CSP', async () => {
    const { html } = await render('examples/web-app.architecture.json');
    const hashes = inlineScriptHashes(html);
    assert.ok(hashes.length >= 1);
    const csp = artifactCsp(html);
    assert.match(csp, /^default-src 'none'; script-src 'sha256-/);
    assert.doesNotMatch(html, /\son[a-z]+="/, 'inline event handlers would need unsafe-hashes');
  });

  it('escapes authored text', async () => {
    const ir = readJson('examples/web-app.architecture.json');
    ir.meta.title = 'T<img src=x onerror=alert(1)>';
    ir.components[0].label = '<b>x</b>"';
    ir.components[0].sublabel = '</text>&';
    const { html } = await renderDiagram(ir);
    assert.equal(html.includes('<img src=x'), false);
    assert.equal(html.includes('<b>x</b>'), false);
    assert.ok(extractSvg(html).includes('&lt;b&gt;x&lt;/b&gt;'));
  });
});
